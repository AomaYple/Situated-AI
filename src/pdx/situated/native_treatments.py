def _path(source: str) -> None:
    if (
        not isinstance(source, str)
        or not source
        or "\\" in source
        or ":" in source
        or PurePosixPath(source).is_absolute()
        or PureWindowsPath(source).drive
        or any(part in {"", ".", ".."} for part in source.split("/"))
        or PurePosixPath(source).as_posix() != source
    ):
        raise ValueError(f"native treatment path is not canonical: {source!r}")


def _family(source: str) -> str:
    parts = source.split("/")
    if "common" in parts:
        index = parts.index("common")
        if index + 1 < len(parts):
            return parts[index + 1]
    return ""


def _ast(node: Assignment | Block | Scalar | None) -> object:
    if isinstance(node, Assignment):
        return ["assignment", node.key, node.op, node.prefix, _ast(node.value)]
    if isinstance(node, Block):
        return ["block", [_ast(item) for item in node.items]]
    if isinstance(node, Scalar):
        return ["scalar", node.text, node.quoted]
    return None


def _digest(node: Assignment | Block | Scalar | None) -> str:
    raw = json.dumps(_ast(node), ensure_ascii=False, separators=(",", ":")).encode()
    return hashlib.sha256(raw).hexdigest()


def _resolve(root: Block, definition: str, field: str) -> tuple[Assignment | None, str]:
    matches = root.all(definition)
    if len(matches) != 1:
        return None, "ambiguous" if matches else "missing"
    node = matches[0]
    if node.op != "=" or node.prefix is not None:
        return None, "ambiguous"
    if field == "__body__":
        return node, "found"
    parts = field.split(".")
    for index, part in enumerate(parts):
        if not isinstance(node.value, Block):
            return None, "missing"
        matches = node.value.all(part)
        if len(matches) != 1:
            return None, "ambiguous" if matches else "missing"
        node = matches[0]
        if node.prefix is not None or (node.op != "=" and index != len(parts) - 1):
            return None, "ambiguous"
    return node, "found"


def _literal(node: Assignment | None, value: str) -> bool:
    return (
        node is not None
        and isinstance(node.value, Scalar)
        and not node.value.quoted
        and node.value.text == value
        and node.op == "="
        and node.prefix is None
    )


def _terminal(node: Assignment) -> str | None:
    value = node.value
    if _zero(node):
        return "zero"
    if not isinstance(value, Block) or not value.items:
        return None
    last = value.items[-1]
    if len(value.items) == 1 and isinstance(last, Assignment) and last.key == "always":
        return "always_false" if _literal(last, "no") else None
    if (
        len(value.items) == 1
        and isinstance(last, Assignment)
        and last.key == "base"
        and _zero(last)
    ):
        return "zero"
    if isinstance(last, Assignment) and last.key in {"value", "multiply"} and _zero(last):
        return "zero"
    return None


def _zero(node: Assignment) -> bool:
    return (
        node.op == "="
        and node.prefix is None
        and isinstance(node.value, Scalar)
        and not node.value.quoted
        and bool(_NUMBER.fullmatch(node.value.text))
        and Decimal(node.value.text) == 0
    )


def _native_terminal(surface: VanillaSurface, node: Assignment) -> str | None:
    terminal = _terminal(node)
    if (
        terminal != "zero"
        or not surface.legal
        or surface.capability != "direct"
        or surface.operation != "additive_score"
        or surface.actor_scope != "country"
        or not isinstance(node.value, Block)
        or len(node.value.items) != 1
        or not isinstance(node.value.items[0], Assignment)
        or node.value.items[0].key != "value"
        or not _zero(node.value.items[0])
    ):
        return terminal
    # These two documented consumers add a modifier to an independent base.
    # A sole initial value=0 is neutral, unlike an explicit reset/multiply tail.
    law = (
        _family(surface.source) == "laws"
        and surface.field == "ai_enact_weight_modifier"
        and surface.target_scope == "scope:law=law"
    )
    interest_group = (
        surface.source == "common/ai_strategies/00_default_strategy.txt"
        and surface.definition == "ai_strategy_default"
        and surface.field == "interest_group_government_weight"
        and surface.target_scope == "scope:interest_group=interest_group"
    )
    return "neutral_zero" if law or interest_group else terminal


def _numeric_shape(node: Assignment, native: Assignment | None = None) -> bool:
    """Validate new syntax; byte-proven native fragments remain opaque evidence.

    The shared numeric validator owns new expression/control syntax. Replacing
    exact native operands, conditions and native-only operations with validation
    placeholders grants no semantics or permission to introduce such syntax.
    Dependencies of retained fragments are checked separately below.
    """
    arithmetic = {"value", "add", "subtract", "multiply", "divide", "min", "max"}
    operands: set[str] = set()
    conditions: set[str] = set()
    original_operations: set[str] = set()

    def collect(value: Block | Scalar | None) -> None:
        if not isinstance(value, Block):
            return
        for item in value.assignments():
            if item.op != "=" or item.prefix is not None:
                continue
            if item.key in arithmetic | {"base"}:
                operands.add(_digest(item.value))
                collect(item.value)
            elif item.key in {"if", "else_if", "else"} and isinstance(item.value, Block):
                for limit in item.value.all("limit"):
                    if limit.op == "=" and limit.prefix is None and isinstance(limit.value, Block):
                        conditions.add(_digest(limit.value))
                collect(
                    Block(
                        [
                            child
                            for child in item.value.items
                            if not isinstance(child, Assignment) or child.key != "limit"
                        ]
                    )
                )
            if item.key not in arithmetic | {"if", "else_if", "else", "desc"}:
                original_operations.add(_digest(item))

    if native is not None:
        operands.add(_digest(native.value))
        collect(native.value)

    def expression(item: Assignment) -> Assignment:
        value = item.value
        if isinstance(value, Scalar):
            if value.quoted or not _NUMBER.fullmatch(value.text):
                if _digest(value) in operands:
                    value = Scalar("1")
                else:
                    raise pdx_eval.UnsupportedPdxError("新增数值操作数必须是未引用的十进制字面量")
        elif isinstance(value, Block):
            value = Scalar("1") if _digest(value) in operands else operations(value)
        return Assignment(item.key, item.op, value, item.prefix, item.line)

    def operations(block: Block) -> Block:
        items: list[Assignment | Block | Scalar] = []
        for item in block.items:
            if not isinstance(item, Assignment):
                items.append(item)
            elif item.key in arithmetic:
                items.append(expression(item))
            elif item.key == "base" and _digest(item) in original_operations:
                converted = expression(item)
                converted.key = "value"
                items.append(converted)
            elif item.key in {"if", "else_if", "else"} and isinstance(item.value, Block):
                body: list[Assignment | Block | Scalar] = []
                for child in item.value.items:
                    if isinstance(child, Assignment) and child.key == "limit":
                        limit_value = child.value
                        if isinstance(limit_value, Block) and _digest(limit_value) in conditions:
                            limit_value = Block([Assignment("always", "=", Scalar("yes"))])
                        body.append(
                            Assignment(child.key, child.op, limit_value, child.prefix, child.line)
                        )
                    else:
                        body.extend(operations(Block([child])).items)
                items.append(Assignment(item.key, item.op, Block(body), item.prefix, item.line))
            elif _digest(item) in original_operations:
                items.append(Assignment("add", "=", Scalar("0")))
            else:
                items.append(item)
        return Block(items, block.line)

    try:
        checked = expression(node)
        native_operations_retained = False
        if native is not None and isinstance(native.value, Block) and isinstance(node.value, Block):
            remaining = iter(node.value.items)
            native_operations_retained = all(
                any(_ast(candidate) == _ast(item) for candidate in remaining)
                for item in native.value.items
            )
        if (
            native is not None
            and isinstance(native.value, Block)
            and native.value.items
            and isinstance(node.value, Block)
            and isinstance(checked.value, Block)
            and not native.value.all("value")
            and not native.value.all("base")
            and not node.value.all("value")
            and native_operations_retained
        ):
            # Some native consumers accumulate from an implicit engine initial
            # value. Every original operation must remain intact and in order;
            # new operations may precede native caps or tails. The placeholder
            # exists solely for shared syntax validation.
            checked.value.items.insert(0, Assignment("value", "=", Scalar("0")))
        pdx_eval._validate_numeric(checked)
    except pdx_eval.UnsupportedPdxError:
        return False
    return True


def _kind(surface: VanillaSurface, node: Assignment) -> str:
    if node.op != "=" or node.prefix is not None:
        return "needs_review"
    family, field, value = _family(surface.source), surface.field, node.value
    if surface.operation in _EXACT_DEFAULT_OPERATIONS.values():
        return (
            "dynamic_numeric"
            if (
                surface.source == "common/ai_strategies/00_default_strategy.txt"
                and surface.definition == "ai_strategy_default"
                and surface.actor_scope == "country"
                and surface.target_scope == "none"
                and surface.capability == "direct"
                and surface.legal
                and _EXACT_DEFAULT_OPERATIONS.get(field) == surface.operation
                and isinstance(value, (Block, Scalar))
            )
            else "needs_review"
        )
    if family == "modifier_type_definitions" and field == "game_data.ai_value":
        if isinstance(value, Scalar) and not value.quoted and _NUMBER.fullmatch(value.text):
            return "static_modifier_valuation"
    elif family == "company_types":
        if field == "ai_will_do" and isinstance(value, Block):
            return "eligibility"
        parts = field.split(".")
        if (
            len(parts) == 3
            and parts[0] == "ai_construction_targets"
            and parts[2] == "level"
            and isinstance(value, Scalar)
            and not value.quoted
            and re.fullmatch(r"[0-9]+", value.text)
        ):
            return "static_construction_cap"
        if field == "ai_weight" and isinstance(value, Block):
            return "dynamic_numeric"
    elif family in {"country_creation", "country_formation"}:
        if field == "ai_will_do" and isinstance(value, Block):
            return "eligibility"
    elif family == "ai_regional_objectives":
        if (
            field == "stances"
            and isinstance(value, Block)
            and all(isinstance(item, Scalar) and not item.quoted for item in value.items)
        ):
            return "static_reference_list"
        if field in {"complete", "invalid"} and isinstance(value, Block):
            return "completion_observation"
        if field in {"on_create", "on_complete", "on_invalid"} and isinstance(value, Block):
            return "lifecycle_effect"
        if field == "possible" and isinstance(value, Block):
            return "eligibility"
        if field == "weight" and isinstance(value, (Scalar, Block)):
            return "dynamic_numeric"
    elif family in _RUNTIME_FAMILIES:
        if surface.operation in _NUMERIC_OPERATIONS and isinstance(value, (Block, Scalar)):
            return "dynamic_numeric"
        if surface.operation in {"eligibility", "predicate"} and isinstance(value, Block):
            return "eligibility"
    elif (
        family == "diplomatic_catalysts"
        and field == "ai_country_goal_recalculation"
        and isinstance(value, Block)
    ):
        return "compound_control"
    return "needs_review"


def _companion_fields(surface: VanillaSurface) -> list[str]:
    family = _family(surface.source)
    fields = set(_QUALIFIERS)
    if family == "company_types" and surface.field.startswith("ai_construction_targets."):
        fields.add(surface.field.rsplit(".", 1)[0])
    if family == "modifier_type_definitions":
        fields.add("game_data")
    if family in {"country_creation", "country_formation"}:
        fields.update(
            {"states", "use_culture_states", "required_num_states", "required_states_fraction"}
        )
    if family == "ai_regional_objectives":
        fields.update({"stances", "complete", "invalid", "on_create", "on_complete", "on_invalid"})
    fields.discard(surface.field)
    return sorted(fields)


class _Sources:
    def __init__(self, sources: Mapping[str, bytes]) -> None:
        self.roots: dict[str, Block] = {}
        self.failures: set[str] = set()
        self.owners: dict[tuple[str, str], list[str]] = defaultdict(list)
        for source, raw in sources.items():
            if not source.endswith(".txt") or not _family(source):
                continue
            try:
                parsed = parse_bytes(raw, path=source)
            except UnicodeDecodeError:
                self.failures.add(source)
                continue
            if parsed.errors:
                self.failures.add(source)
                continue
            self.roots[source] = parsed.root
            for node in parsed.root.assignments():
                if not node.is_variable:
                    self.owners[_family(source), node.key].append(source)


class _Dependencies:
    """Trace supplied named values/triggers, with source bytes and AST identity.

    This is a conservative dependency audit, never a named-expression evaluator.
    Unknown direct numeric names, missing/duplicate definitions and cycles cannot
    prove native retention. New runtime getter permissions are not inferred.
    """

    def __init__(
        self,
        native: _Sources,
        effective: _Sources,
        native_bytes: Mapping[str, bytes],
        effective_bytes: Mapping[str, bytes],
        source_hashes: Mapping[str, str],
    ) -> None:
        self.native, self.effective = native, effective
        self.native_bytes, self.effective_bytes = native_bytes, effective_bytes
        self.symbols: dict[str, set[tuple[str, str]]] = defaultdict(set)
        for family, name in {*native.owners, *effective.owners}:
            if family in {"script_values", "scripted_triggers"}:
                self.symbols[name].add((family, name))
        self.cache: dict[tuple[str, str], tuple[dict[tuple[str, str], dict[str, Any]], bool]] = {}
        # With an incomplete definition index, an unrecognized condition name
        # could be a custom trigger rather than a built-in. Do not infer safety
        # from a caller supplying only the consumer files.
        self.source_gaps: list[dict[str, Any]] = []
        for source in sorted(set(source_hashes) | set(effective.failures)):
            if not source.endswith(".txt") or _family(source) not in {
                "script_values",
                "scripted_triggers",
            }:
                continue
            if source in native.roots and source in effective.roots:
                continue
            status = (
                "source_parse_failure"
                if source in native.failures or source in effective.failures
                else "source_missing"
            )
            self.source_gaps.append(
                {
                    "family": _family(source),
                    "definition": f"@source:{source}",
                    "status": status,
                    "native_source": source,
                    "effective_source": source if source in effective_bytes else None,
                    "native_source_sha256": hashlib.sha256(native_bytes[source]).hexdigest()
                    if source in native_bytes
                    else None,
                    "effective_source_sha256": hashlib.sha256(effective_bytes[source]).hexdigest()
                    if source in effective_bytes
                    else None,
                    "native_ast_sha256": None,
                    "effective_ast_sha256": None,
                }
            )

    def references(self, node: Assignment, *, numeric: bool = False) -> set[tuple[str, str]]:
        found: set[tuple[str, str]] = set()

        def scalar(value: Scalar, *, numeric_value: bool) -> None:
            for word in re.findall(r"[A-Za-z_][A-Za-z_0-9]*", value.text):
                found.update(self.symbols.get(word, ()))
            if (
                numeric_value
                and not value.quoted
                and re.fullmatch(r"[a-z][a-z_0-9]*", value.text)
                and value.text not in {"yes", "no"}
                and value.text not in self.symbols
            ):
                found.add(("script_values", value.text))

        def visit(value: Block | Scalar | None, *, numeric_value: bool = False) -> None:
            if isinstance(value, Scalar):
                scalar(value, numeric_value=numeric_value)
            elif isinstance(value, Block):
                for item in value.items:
                    if isinstance(item, Assignment):
                        if item.key in {"desc", "save_temporary_value_as"}:
                            continue
                        found.update(self.symbols.get(item.key, ()))
                        visit(
                            item.value,
                            numeric_value=numeric_value
                            and item.key
                            in {
                                "value",
                                "base",
                                "add",
                                "subtract",
                                "multiply",
                                "divide",
                                "min",
                                "max",
                                "if",
                                "else_if",
                                "else",
                            },
                        )
                    elif isinstance(item, Scalar):
                        scalar(item, numeric_value=False)
                    else:
                        visit(item)

        visit(node.value, numeric_value=numeric)
        return found

    @staticmethod
    def definition(
        sources: _Sources, family: str, name: str
    ) -> tuple[str | None, Assignment | None]:
        owners = sources.owners.get((family, name), [])
        if len(owners) != 1 or any(_family(source) == family for source in sources.failures):
            return None, None
        source = owners[0]
        node, state = _resolve(sources.roots[source], name, "__body__")
        return (source, node) if state == "found" else (None, None)

    def proof(
        self,
        symbol: tuple[str, str],
        trail: frozenset[tuple[str, str]] = frozenset(),
    ) -> tuple[dict[tuple[str, str], dict[str, Any]], bool]:
        if symbol in trail:
            return {}, False
        if symbol in self.cache:
            return self.cache[symbol]
        family, name = symbol
        before_source, before = self.definition(self.native, family, name)
        after_source, after = self.definition(self.effective, family, name)
        if before is None or after is None:
            status = "unproven"
        else:
            status = "retained" if _ast(before) == _ast(after) else "changed"
        row = {
            "family": family,
            "definition": name,
            "status": status,
            "native_source": before_source,
            "effective_source": after_source,
            "native_source_sha256": hashlib.sha256(self.native_bytes[before_source]).hexdigest()
            if before_source is not None
            else None,
            "effective_source_sha256": hashlib.sha256(
                self.effective_bytes[after_source]
            ).hexdigest()
            if after_source is not None
            else None,
            "native_ast_sha256": _digest(before) if before is not None else None,
            "effective_ast_sha256": _digest(after) if after is not None else None,
        }
        proofs = {symbol: row}
        proven = status == "retained"
        children: set[tuple[str, str]] = set()
        for node in (before, after):
            if node is not None:
                children.update(self.references(node, numeric=family == "script_values"))
        for child in sorted(children):
            child_rows, child_proven = self.proof(child, trail | {symbol})
            proofs.update(child_rows)
            proven = proven and child_proven
        if not proven and row["status"] == "retained":
            row["status"] = "dependency_unproven"
        # A cycle-dependent result is conservative for every entry point.
        self.cache[symbol] = proofs, proven
        return proofs, proven

    def check(self, *nodes: Assignment, numeric: bool) -> tuple[list[dict[str, Any]], bool]:
        proofs: dict[tuple[str, str], dict[str, Any]] = {}
        proven = not self.source_gaps
        references = set().union(*(self.references(node, numeric=numeric) for node in nodes))
        for symbol in sorted(references):
            rows, valid = self.proof(symbol)
            proofs.update(rows)
            proven = proven and valid
        return [proofs[key] for key in sorted(proofs)] + self.source_gaps, proven


def _contains_value_dependency(value: Block | Scalar | None, names: set[str]) -> bool:
    # No named dependencies are granted here, even acyclic ones. In particular,
    # trigger-side references must not hide self/indirect cycles or aliases.
    if isinstance(value, Scalar):
        return bool(names.intersection(re.findall(r"[A-Za-z_][A-Za-z_0-9]*", value.text)))
    if not isinstance(value, Block):
        return False
    return any(
        (
            bool(names.intersection(re.findall(r"[A-Za-z_][A-Za-z_0-9]*", item.key)))
            or _contains_value_dependency(item.value, names)
        )
        if isinstance(item, Assignment)
        else _contains_value_dependency(item, names)
        for item in value.items
    )


def _registered_numeric_value(
    surface: VanillaSurface,
    node: Assignment,
    effective: _Sources,
    generated_sources: Mapping[str, bytes],
) -> dict[str, str] | None:
    # Lazy import: the adapter imports situated code while loading its contracts.
    from .. import decision_adapters as adapters  # noqa: PLC0415, TID252

    if (
        surface.source != adapters._FLEET_SOURCE
        or (surface.definition, *surface.field.split(".")) != adapters._FLEET_FIELD
        or not _literal(node, adapters._FLEET_VALUE)
        or adapters._VALUE_SOURCE not in generated_sources
        or any(_family(source) == "script_values" for source in effective.failures)
        or effective.owners["script_values", adapters._FLEET_VALUE] != [adapters._VALUE_SOURCE]
    ):
        return None
    root = effective.roots.get(adapters._VALUE_SOURCE)
    if root is None:
        return None
    value, state = _resolve(root, adapters._FLEET_VALUE, "__body__")
    names = {name for family, name in effective.owners if family == "script_values"}
    if (
        state != "found"
        or value is None
        or not isinstance(value.value, Block)
        or not _numeric_shape(value)
        or _contains_value_dependency(value.value, names)
    ):
        return None
    return {
        "source": adapters._VALUE_SOURCE,
        "definition": adapters._FLEET_VALUE,
        "ast_sha256": _digest(value),
        "source_sha256": hashlib.sha256(generated_sources[adapters._VALUE_SOURCE]).hexdigest(),
    }


def _coverage_rows(
    inventory: VanillaInventory, coverage: Mapping[str, Any] | None
) -> tuple[dict[str, dict[str, Any]], list[str]]:
    if coverage is None:
        return {}, []
    if (
        coverage.get("baseline_id") != inventory.baseline_id
        or type(coverage.get("denominator")) is not int
        or coverage.get("denominator") != inventory.discovered_count
        or coverage.get("scope_hash") != inventory.scope_hash
        or coverage.get("source_hashes") != inventory.source_hashes
        or not isinstance(coverage.get("rows"), list)
    ):
        return {}, ["coverage_receipt_identity_unproven"]
    rows: dict[str, dict[str, Any]] = {}
    for row in coverage["rows"]:
        if not isinstance(row, dict) or not isinstance(row.get("declaration_id"), str):
            return {}, ["coverage_receipt_rows_invalid"]
        key = row["declaration_id"]
        if key in rows:
            return {}, ["coverage_receipt_rows_ambiguous"]
        rows[key] = row
    return rows, []


def _numeric_binding(surface: VanillaSurface, row: Mapping[str, Any]) -> bool:
    for key, value in asdict(surface).items():
        observed = row.get(key)
        if key == "scope_evidence":
            if not isinstance(observed, (tuple, list)) or tuple(observed) != value:
                return False
        elif type(observed) is not type(value) or observed != value:
            return False
    return (
        row.get("source") == surface.source
        and row.get("definition") == surface.definition
        and row.get("field") == surface.field
        and row.get("coverage_status") == "actual_covered"
        and row.get("legal") is True
        and row.get("unknown_scope") is False
        and isinstance(row.get("covered_actions"), list)
        and bool(row["covered_actions"])
        and all(isinstance(action, str) and action for action in row["covered_actions"])
        and len(set(row["covered_actions"])) == len(row["covered_actions"])
        and isinstance(row.get("matched_actions"), list)
        and all(action in row["matched_actions"] for action in row["covered_actions"])
        and row.get("binding_issues") == {}
    )


def native_treatments(
    inventory: VanillaInventory,
    native_sources: Mapping[str, bytes],
    generated_sources: Mapping[str, bytes],
    *,
    coverage: Mapping[str, Any] | None = None,
    production_complete: bool = False,
) -> dict[str, Any]:
    """Retain every declaration and independently check native protection duties.

    Native source hash drift and unsafe/alias paths fail rather than accepting
    a different baseline. Missing bytes, malformed/duplicate declarations and
    unproven scopes remain explicit rows; none are reclassified unsupported.
    """
    if type(production_complete) is not bool:
        raise ValueError("native treatment production manifest assertion must be boolean")
    aliases: dict[str, str] = {}
    for mapping in (native_sources, generated_sources):
        seen: set[str] = set()
        for source, raw in mapping.items():
            _path(source)
            if not isinstance(raw, bytes):
                raise ValueError("native treatment sources must be bytes")
            if source.casefold() in seen:
                raise ValueError("native treatment path alias")
            if aliases.get(source.casefold(), source) != source:
                raise ValueError("native treatment path alias")
            aliases[source.casefold()] = source
            seen.add(source.casefold())
    for source, raw in native_sources.items():
        if hashlib.sha256(raw).hexdigest() != inventory.source_hashes.get(source):
            raise ValueError(f"native treatment source SHA mismatch: {source}")
    ids = [surface.declaration_id for surface in inventory.surfaces]
    if len(set(ids)) != len(ids):
        raise ValueError("native treatment declaration IDs are duplicated")
    native = _Sources(native_sources)
    effective_bytes = {**native_sources, **generated_sources}
    effective = _Sources(effective_bytes)
    dependencies = _Dependencies(
        native, effective, native_sources, effective_bytes, inventory.source_hashes
    )
    covered, receipt_issues = _coverage_rows(inventory, coverage)
    unknown_scopes = set(inventory.unknown_scopes)
    rows: list[dict[str, Any]] = []
    for surface in inventory.surfaces:
        row: dict[str, Any] = {
            "declaration_id": surface.declaration_id,
            "surface_id": surface.surface_id,
            "source": surface.source,
            "definition": surface.definition,
            "field": surface.field,
            "source_line": surface.source_line,
            "declaration_occurrence": surface.declaration_occurrence,
            "ambiguity": surface.ambiguity,
            "parent_field": surface.parent_field,
            "actor_scope": surface.actor_scope,
            "target_scope": surface.target_scope,
            "native_operation": surface.operation,
            "native_capability": surface.capability,
            "native_inventory_status": surface.status,
            "native_legal": surface.legal,
            "scope_evidence": list(surface.scope_evidence),
            "interface_kind": "needs_review",
            "status": "missing_evidence",
            "ast_status": "missing",
            "native_ast_sha256": None,
            "effective_ast_sha256": None,
            "native_terminal": None,
            "effective_origin": "generated_override"
            if surface.source in generated_sources
            else "native_inherited",
            "companions": [],
            "issues": [],
            "implemented_numeric": False,
            "numeric_actions": [],
            "resolved_numeric_value": None,
            "dependencies": [],
            "business_complete": False,
        }
        rows.append(row)
        issues = row["issues"]
        nroot = native.roots.get(surface.source)
        if nroot is None:
            issues.append(
                "native_parse_failure"
                if surface.source in native.failures
                else "native_bytes_missing"
            )
            continue
        node, resolution = _resolve(nroot, surface.definition, surface.field)
        if node is None:
            row["ast_status"] = resolution
            issues.append(f"native_field_{resolution}")
            continue
        row["native_ast_sha256"] = _digest(node)
        row["native_terminal"] = _native_terminal(surface, node)
        row["interface_kind"] = _kind(surface, node)
        family = _family(surface.source)
        if node.line != surface.source_line:
            issues.append("native_source_line_mismatch")
            continue
        if len(native.owners[family, surface.definition]) != 1:
            row["ast_status"] = "ambiguous"
            issues.append("native_definition_ambiguous")
            continue
        if surface.source not in generated_sources and not production_complete:
            issues.append("production_manifest_incomplete")
            continue
        eroot = effective.roots.get(surface.source)
        if eroot is None:
            issues.append("production_parse_failure")
            continue
        if any(_family(source) == family for source in effective.failures):
            issues.append("production_family_parse_failure")
            continue
        enode, resolution = _resolve(eroot, surface.definition, surface.field)
        if enode is None:
            row["ast_status"] = resolution
            issues.append(f"production_field_{resolution}")
            continue
        if len(effective.owners[family, surface.definition]) != 1:
            row["ast_status"] = "ambiguous"
            issues.append("production_definition_ambiguous")
            continue
        row["effective_ast_sha256"] = _digest(enode)
        same = _ast(node) == _ast(enode)
        row["ast_status"] = "retained" if same else "changed"
        kind = row["interface_kind"]
        effective_consumer = enode
        if not same and kind == "dynamic_numeric" and not _numeric_shape(enode, node):
            row["resolved_numeric_value"] = _registered_numeric_value(
                surface, enode, effective, generated_sources
            )
            if row["resolved_numeric_value"] is None:
                issues.append("generated_numeric_shape_unproven")
            else:
                resolved = row["resolved_numeric_value"]
                helper, state = _resolve(
                    effective.roots[resolved["source"]], resolved["definition"], "__body__"
                )
                assert helper is not None
                assert state == "found"
                # The new helper name has an exact registered source/consumer
                # proof above. Its actual body still requires dependency audit.
                effective_consumer = helper
        main_proofs, dependencies_proven = dependencies.check(
            node, effective_consumer, numeric=kind == "dynamic_numeric"
        )
        dependency_proofs = {(proof["family"], proof["definition"]): proof for proof in main_proofs}
        for field in _companion_fields(surface):
            before, bstate = _resolve(nroot, surface.definition, field)
            after, astate = _resolve(eroot, surface.definition, field)
            if before is None and after is None and bstate == astate == "missing":
                continue
            companion_same = bstate == astate == "found" and _ast(before) == _ast(after)
            companion_proofs, companion_dependencies_proven = dependencies.check(
                *(item for item in (before, after) if item is not None), numeric=False
            )
            dependencies_proven = dependencies_proven and companion_dependencies_proven
            dependency_proofs.update(
                ((proof["family"], proof["definition"]), proof) for proof in companion_proofs
            )
            row["companions"].append(
                {
                    "field": field,
                    "retained": companion_same and companion_dependencies_proven,
                    "ast_retained": companion_same,
                    "dependencies": companion_proofs,
                    "native_ast_sha256": _digest(before),
                    "effective_ast_sha256": _digest(after),
                }
            )
            if not companion_same:
                issues.append(f"native_companion_changed:{field}")
            if not companion_dependencies_proven:
                issues.append(f"native_companion_dependency_unproven:{field}")
        row["dependencies"] = [dependency_proofs[key] for key in sorted(dependency_proofs)]
        if not dependencies_proven:
            issues.append("native_dependency_unproven")
        if not same:
            if kind == "eligibility":
                issues.append("native_eligibility_changed")
            elif kind == "completion_observation":
                issues.append("completion_condition_changed")
            elif kind == "lifecycle_effect":
                issues.append("lifecycle_effect_changed")
            if row["native_terminal"] == "zero":
                issues.append("native_zero_changed_unproven")
        unproven = (
            kind == "needs_review"
            or not surface.legal
            or bool(surface.ambiguity)
            or surface.surface_id in unknown_scopes
            or bool(inventory.parse_failures)
            or not dependencies_proven
        )
        if unproven:
            row["status"] = "needs_review"
            issues.append("native_interface_or_scope_needs_review")
        elif same and not issues:
            row["status"] = "retained_native"
        elif (
            kind == "dynamic_numeric"
            and not issues
            and _numeric_binding(surface, covered.get(surface.declaration_id, {}))
        ):
            row["status"] = "implemented_numeric"
            row["implemented_numeric"] = True
            row["numeric_actions"] = list(covered[surface.declaration_id]["covered_actions"])
        else:
            row["status"] = "changed_native"
    counts = Counter(row["status"] for row in rows)
    return {
        "schema": 1,
        "evidence_category": "static_check",
        "baseline_id": inventory.baseline_id,
        "scope_hash": inventory.scope_hash,
        "denominator": len(inventory.surfaces),
        "source_hashes_verified": {
            source: inventory.source_hashes[source] for source in sorted(native_sources)
        },
        "production_hashes": {
            source: hashlib.sha256(raw).hexdigest()
            for source, raw in sorted(generated_sources.items())
        },
        "production_manifest_complete_asserted": production_complete,
        "counts": {status: counts[status] for status in _STATUSES},
        "interface_counts": dict(sorted(Counter(row["interface_kind"] for row in rows).items())),
        "receipt_issues": receipt_issues,
        "rows": rows,
        "business_complete": False,
        "evidence": "typed_native_ast_protection_and_existing_numeric_mapping_only",
        "limits": [
            "retained_native is not implemented_numeric or functional acceptance",
            "coverage bindings do not prove generated expression equivalence or native tails",
            "numeric mappings do not prove business depth, AI behavior or runtime scope",
            "native inheritance relies on caller completeness; omitted outputs cannot be discovered",
            "modifier code-side route support remains unproven for individual types",
        ],
    }

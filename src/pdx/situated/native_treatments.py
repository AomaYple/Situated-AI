def _path(source: str) -> None:
    if (
        not isinstance(source, str)
        or not source
        or "\\" in source
        or ":" in source
        or PurePosixPath(source).is_absolute()
        or PureWindowsPath(source).drive
        or any(part in {"", ".", ".."} for part in source.split("/"))
        or PurePosixPath(source).as_posix() != source
    ):
        raise ValueError(f"native treatment path is not canonical: {source!r}")


def _family(source: str) -> str:
    parts = source.split("/")
    if "common" in parts:
        index = parts.index("common")
        if index + 1 < len(parts):
            return parts[index + 1]
    return ""


def _ast(node: Assignment | Block | Scalar | None) -> object:
    if isinstance(node, Assignment):
        return ["assignment", node.key, node.op, node.prefix, _ast(node.value)]
    if isinstance(node, Block):
        return ["block", [_ast(item) for item in node.items]]
    if isinstance(node, Scalar):
        return ["scalar", node.text, node.quoted]
    return None


def _digest(node: Assignment | Block | Scalar | None) -> str:
    raw = json.dumps(_ast(node), ensure_ascii=False, separators=(",", ":")).encode()
    return hashlib.sha256(raw).hexdigest()


def _resolve(root: Block, definition: str, field: str) -> tuple[Assignment | None, str]:
    matches = root.all(definition)
    if len(matches) != 1:
        return None, "ambiguous" if matches else "missing"
    node = matches[0]
    if node.op != "=" or node.prefix is not None:
        return None, "ambiguous"
    if field == "__body__":
        return node, "found"
    parts = field.split(".")
    for index, part in enumerate(parts):
        if not isinstance(node.value, Block):
            return None, "missing"
        matches = node.value.all(part)
        if len(matches) != 1:
            return None, "ambiguous" if matches else "missing"
        node = matches[0]
        if node.prefix is not None or (node.op != "=" and index != len(parts) - 1):
            return None, "ambiguous"
    return node, "found"


def _declarations(root: Block, definition: str, field: str) -> list[Assignment]:
    """Locate physical declarations without choosing engine duplicate semantics."""
    nodes = root.all(definition)
    if field != "__body__":
        for part in field.split("."):
            nodes = [
                child
                for node in nodes
                if node.op == "=" and node.prefix is None and isinstance(node.value, Block)
                for child in node.value.all(part)
            ]
    return [node for node in nodes if node.prefix is None]


def _declaration(root: Block, surface: VanillaSurface) -> Assignment | None:
    occurrence = surface.declaration_occurrence
    if type(occurrence) is not int or occurrence < 1:
        return None
    nodes = _declarations(root, surface.definition, surface.field)
    return nodes[occurrence - 1] if occurrence <= len(nodes) else None


def _context_digest(surface: VanillaSurface) -> str:
    raw = json.dumps(asdict(surface), sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(raw.encode()).hexdigest()


def _variable_boundary(before: Block, after: Block) -> bool:
    """Retain lexical declarations and resolve earlier bindings, without evaluation."""

    def inspect(root: Block) -> tuple[list[object], bool]:
        declarations: list[object] = []

        def scalar_closed(value: Scalar, available: set[str]) -> bool:
            names = set(re.findall(r"@[A-Za-z_][A-Za-z_0-9]*", value.text))
            for expression in re.findall(r"@\[([^\]]*)\]", value.text):
                names.update(
                    "@" + name for name in re.findall(r"[A-Za-z_][A-Za-z_0-9]*", expression)
                )
            return names <= available

        def visit(block: Block, inherited: set[str], path: tuple[str, ...]) -> bool:
            available = set(inherited)
            local: set[str] = set()
            occurrences: Counter[str] = Counter()
            for item in block.items:
                if not isinstance(item, Assignment):
                    if isinstance(item, Scalar) and not scalar_closed(item, available):
                        return False
                    continue
                occurrences[item.full_key] += 1
                child_path = (*path, f"{item.full_key}:{occurrences[item.full_key]}")
                if item.is_variable:
                    if (
                        item.key in local
                        or item.op != "="
                        or item.prefix is not None
                        or not isinstance(item.value, Scalar)
                        or not scalar_closed(item.value, available)
                    ):
                        return False
                    declarations.append([path, _ast(item)])
                    local.add(item.key)
                    available.add(item.key)
                elif item.key != "desc":
                    if isinstance(item.value, Scalar) and not scalar_closed(item.value, available):
                        return False
                    if isinstance(item.value, Block) and not visit(
                        item.value, available, child_path
                    ):
                        return False
            return True

        return declarations, visit(root, set(), ())

    original, before_closed = inspect(before)
    current, after_closed = inspect(after)
    return before_closed and after_closed and original == current


def _literal(node: Assignment | None, value: str) -> bool:
    return (
        node is not None
        and isinstance(node.value, Scalar)
        and not node.value.quoted
        and node.value.text == value
        and node.op == "="
        and node.prefix is None
    )


def _terminal(node: Assignment) -> str | None:
    value = node.value
    if _zero(node):
        return "zero"
    if not isinstance(value, Block) or not value.items:
        return None
    last = value.items[-1]
    if len(value.items) == 1 and isinstance(last, Assignment) and last.key == "always":
        return "always_false" if _literal(last, "no") else None
    if (
        len(value.items) == 1
        and isinstance(last, Assignment)
        and last.key == "base"
        and _zero(last)
    ):
        return "zero"
    if isinstance(last, Assignment) and last.key in {"value", "multiply"} and _zero(last):
        return "zero"
    return None


def _zero(node: Assignment) -> bool:
    return (
        node.op == "="
        and node.prefix is None
        and isinstance(node.value, Scalar)
        and not node.value.quoted
        and bool(_NUMBER.fullmatch(node.value.text))
        and Decimal(node.value.text) == 0
    )


def _native_terminal(surface: VanillaSurface, node: Assignment) -> str | None:
    terminal = _terminal(node)
    if (
        terminal != "zero"
        or not surface.legal
        or surface.capability != "direct"
        or surface.operation != "additive_score"
        or surface.actor_scope != "country"
        or not isinstance(node.value, Block)
        or len(node.value.items) != 1
        or not isinstance(node.value.items[0], Assignment)
        or node.value.items[0].key != "value"
        or not _zero(node.value.items[0])
    ):
        return terminal
    # These two documented consumers add a modifier to an independent base.
    # A sole initial value=0 is neutral, unlike an explicit reset/multiply tail.
    law = (
        _family(surface.source) == "laws"
        and surface.field == "ai_enact_weight_modifier"
        and surface.target_scope == "scope:law=law"
    )
    interest_group = (
        surface.source == "common/ai_strategies/00_default_strategy.txt"
        and surface.definition == "ai_strategy_default"
        and surface.field == "interest_group_government_weight"
        and surface.target_scope == "scope:interest_group=interest_group"
    )
    return "neutral_zero" if law or interest_group else terminal


def _numeric_shape(node: Assignment, native: Assignment | None = None) -> bool:
    """Validate new syntax; byte-proven native fragments remain opaque evidence.

    The shared numeric validator owns new expression/control syntax. Replacing
    exact native operands, conditions and native-only operations with validation
    placeholders grants no semantics or permission to introduce such syntax.
    Dependencies of retained fragments are checked separately below.
    """
    arithmetic = {"value", "add", "subtract", "multiply", "divide", "min", "max"}
    operands: set[str] = set()
    conditions: set[str] = set()
    original_operations: set[str] = set()

    def collect(value: Block | Scalar | None) -> None:
        if not isinstance(value, Block):
            return
        for item in value.assignments():
            if item.op != "=" or item.prefix is not None:
                continue
            if item.key in arithmetic | {"base"}:
                operands.add(_digest(item.value))
                collect(item.value)
            elif item.key in {"if", "else_if", "else"} and isinstance(item.value, Block):
                for limit in item.value.all("limit"):
                    if limit.op == "=" and limit.prefix is None and isinstance(limit.value, Block):
                        conditions.add(_digest(limit.value))
                collect(
                    Block(
                        [
                            child
                            for child in item.value.items
                            if not isinstance(child, Assignment) or child.key != "limit"
                        ]
                    )
                )
            if item.key not in arithmetic | {"if", "else_if", "else", "desc"}:
                original_operations.add(_digest(item))

    if native is not None:
        operands.add(_digest(native.value))
        collect(native.value)

    def expression(item: Assignment) -> Assignment:
        value = item.value
        if isinstance(value, Scalar):
            if value.quoted or not _NUMBER.fullmatch(value.text):
                if _digest(value) in operands:
                    value = Scalar("1")
                else:
                    raise pdx_eval.UnsupportedPdxError("新增数值操作数必须是未引用的十进制字面量")
        elif isinstance(value, Block):
            value = Scalar("1") if _digest(value) in operands else operations(value)
        return Assignment(item.key, item.op, value, item.prefix, item.line)

    def operations(block: Block) -> Block:
        items: list[Assignment | Block | Scalar] = []
        for item in block.items:
            if not isinstance(item, Assignment):
                items.append(item)
            elif item.key in arithmetic:
                items.append(expression(item))
            elif item.key == "base" and _digest(item) in original_operations:
                converted = expression(item)
                converted.key = "value"
                items.append(converted)
            elif item.key in {"if", "else_if", "else"} and isinstance(item.value, Block):
                body: list[Assignment | Block | Scalar] = []
                for child in item.value.items:
                    if isinstance(child, Assignment) and child.key == "limit":
                        limit_value = child.value
                        if isinstance(limit_value, Block) and _digest(limit_value) in conditions:
                            limit_value = Block([Assignment("always", "=", Scalar("yes"))])
                        body.append(
                            Assignment(child.key, child.op, limit_value, child.prefix, child.line)
                        )
                    else:
                        body.extend(operations(Block([child])).items)
                items.append(Assignment(item.key, item.op, Block(body), item.prefix, item.line))
            elif _digest(item) in original_operations:
                items.append(Assignment("add", "=", Scalar("0")))
            else:
                items.append(item)
        return Block(items, block.line)

    try:
        checked = expression(node)
        native_operations_retained = False
        if native is not None and isinstance(native.value, Block) and isinstance(node.value, Block):
            remaining = iter(node.value.items)
            native_operations_retained = all(
                any(_ast(candidate) == _ast(item) for candidate in remaining)
                for item in native.value.items
            )
        if (
            native is not None
            and isinstance(native.value, Block)
            and native.value.items
            and isinstance(node.value, Block)
            and isinstance(checked.value, Block)
            and not native.value.all("value")
            and not native.value.all("base")
            and not node.value.all("value")
            and native_operations_retained
        ):
            # Some native consumers accumulate from an implicit engine initial
            # value. Every original operation must remain intact and in order;
            # new operations may precede native caps or tails. The placeholder
            # exists solely for shared syntax validation.
            checked.value.items.insert(0, Assignment("value", "=", Scalar("0")))
        pdx_eval._validate_numeric(checked)
    except pdx_eval.UnsupportedPdxError:
        return False
    return True


def _kind(surface: VanillaSurface, node: Assignment) -> str:
    if node.op != "=" or node.prefix is not None:
        return "needs_review"
    family, field, value = _family(surface.source), surface.field, node.value
    if surface.operation == "first_nonzero_active_change_law_chance_else_default":
        return (
            "dynamic_numeric"
            if (
                version_contracts.is_115()
                and surface.source == "common/ai_strategies/00_default_strategy.txt"
                and surface.definition == "ai_strategy_default"
                and surface.field == "change_law_chance"
                and surface.actor_scope == "country"
                and surface.target_scope == "none"
                and surface.capability == "direct"
                and surface.legal
                and isinstance(value, (Block, Scalar))
            )
            else "needs_review"
        )
    if surface.operation in _EXACT_DEFAULT_OPERATIONS.values():
        return (
            "dynamic_numeric"
            if (
                surface.source == "common/ai_strategies/00_default_strategy.txt"
                and surface.definition == "ai_strategy_default"
                and surface.actor_scope == "country"
                and surface.target_scope == "none"
                and surface.capability == "direct"
                and surface.legal
                and _EXACT_DEFAULT_OPERATIONS.get(field) == surface.operation
                and isinstance(value, (Block, Scalar))
            )
            else "needs_review"
        )
    if family == "modifier_type_definitions" and field == "game_data.ai_value":
        if isinstance(value, Scalar) and not value.quoted and _NUMBER.fullmatch(value.text):
            return "static_modifier_valuation"
    elif family == "company_types":
        if field == "ai_will_do" and isinstance(value, Block):
            return "eligibility"
        parts = field.split(".")
        if (
            len(parts) == 3
            and parts[0] == "ai_construction_targets"
            and parts[2] == "level"
            and isinstance(value, Scalar)
            and not value.quoted
            and re.fullmatch(r"[0-9]+", value.text)
        ):
            return "static_construction_cap"
        if field == "ai_weight" and isinstance(value, Block):
            return "dynamic_numeric"
    elif family in {"country_creation", "country_formation"}:
        if field == "ai_will_do" and isinstance(value, Block):
            return "eligibility"
    elif family == "ai_regional_objectives":
        if (
            field == "stances"
            and isinstance(value, Block)
            and all(isinstance(item, Scalar) and not item.quoted for item in value.items)
        ):
            return "static_reference_list"
        if field in {"complete", "invalid"} and isinstance(value, Block):
            return "completion_observation"
        if field in {"on_create", "on_complete", "on_invalid"} and isinstance(value, Block):
            return "lifecycle_effect"
        if field == "possible" and isinstance(value, Block):
            return "eligibility"
        if field == "weight" and isinstance(value, (Scalar, Block)):
            return "dynamic_numeric"
    elif family == "decrees":
        if (
            version_contracts.active_version() == "1.15.1"
            and surface.source == "common/decrees/00_decree.txt"
            and surface.definition == "decree_road_maintenance"
            and field == "ai_weight"
            and surface.actor_scope == "state"
            and surface.target_scope == "scope:country=country"
            and surface.operation == "relative_weight"
            and surface.capability == "direct"
            and surface.legal
            and isinstance(value, Block)
        ):
            return "dynamic_numeric"
    elif family in _RUNTIME_FAMILIES:
        if surface.operation in _NUMERIC_OPERATIONS and isinstance(value, (Block, Scalar)):
            return "dynamic_numeric"
        if surface.operation in {"eligibility", "predicate"} and isinstance(value, Block):
            return "eligibility"
    elif (
        family == "diplomatic_catalysts"
        and field == "ai_country_goal_recalculation"
        and isinstance(value, Block)
    ):
        return "compound_control"
    return "needs_review"


def _companion_fields(surface: VanillaSurface) -> list[str]:
    family = _family(surface.source)
    fields = set(_QUALIFIERS)
    if family == "company_types" and surface.field.startswith("ai_construction_targets."):
        fields.add(surface.field.rsplit(".", 1)[0])
    if family == "modifier_type_definitions":
        fields.add("game_data")
    if family in {"country_creation", "country_formation"}:
        fields.update(
            {"states", "use_culture_states", "required_num_states", "required_states_fraction"}
        )
    if family == "decrees":
        fields.update({"cost", "country_trigger", "state_trigger", "unlocking_laws"})
    if family == "ai_regional_objectives":
        fields.update({"stances", "complete", "invalid", "on_create", "on_complete", "on_invalid"})
    fields.discard(surface.field)
    return sorted(fields)


class _Sources:
    """Read-only AST indexes owned by one audit, with exact-byte local reuse.

    Native and effective sources are read, never mutated by this module. Only
    an identical path and immutable byte payload can share a parsed root;
    owner indexes remain separate and retain the supplied declaration order.
    Nothing is retained across audits or grants new source permissions.
    """

    def __init__(self, sources: Mapping[str, bytes], *, reuse: _Sources | None = None) -> None:
        self._bytes = dict(sources)
        self.roots: dict[str, Block] = {}
        self.failures: set[str] = set()
        self.owners: dict[tuple[str, str], list[str]] = defaultdict(list)
        for source, raw in sources.items():
            if not source.endswith(".txt"):
                continue
            if reuse is not None and reuse._bytes.get(source) == raw:
                if source in reuse.failures:
                    self.failures.add(source)
                    continue
                root = reuse.roots[source]
            else:
                try:
                    parsed = parse_bytes(raw, path=source)
                except UnicodeDecodeError:
                    self.failures.add(source)
                    continue
                if parsed.errors:
                    self.failures.add(source)
                    continue
                root = parsed.root
            self.roots[source] = root
            for node in root.assignments():
                if not node.is_variable:
                    self.owners[_family(source), node.key].append(source)


class _Dependencies:
    """Trace supplied named values/triggers, with source bytes and AST identity.

    This is a conservative dependency audit, never a named-expression evaluator.
    Unknown direct numeric names, missing/duplicate definitions and cycles cannot
    prove native retention. New runtime getter permissions are not inferred.
    """

    def __init__(
        self,
        native: _Sources,
        effective: _Sources,
        native_bytes: Mapping[str, bytes],
        effective_bytes: Mapping[str, bytes],
        source_hashes: Mapping[str, str],
        *,
        production_complete: bool = False,
        _metadata: _AuditMetadata | None = None,
    ) -> None:
        if _metadata is not None and type(_metadata) is not _AuditMetadata:
            raise TypeError("audit metadata must be a byte-bound audit owner")
        self.native, self.effective = native, effective
        self.production_complete = production_complete
        self._metadata = _metadata
        # Bytes are immutable; snapshot the mappings so every proof/cache in
        # this audit instance refers to the same supplied candidate inputs.
        self.native_bytes, self.effective_bytes = dict(native_bytes), dict(effective_bytes)
        self.parameter_input_mappings = (native_bytes, effective_bytes)
        self.symbols: dict[str, set[tuple[str, str]]] = defaultdict(set)
        for family, name in {*native.owners, *effective.owners}:
            if family in {"script_values", "scripted_triggers"}:
                self.symbols[name].add((family, name))
        self.cache: dict[tuple[str, str], tuple[dict[tuple[str, str], dict[str, Any]], bool]] = {}
        self.recursive_inheritance: dict[tuple[str, str], dict[str, Any]] = {}
        self.country_parameter_proof: dict[str, Any] | None = None
        self.country_parameter_helpers: set[str] = set()
        self.country_contract_checked = False
        self.country_contract_present = False
        self.reader_parameter_cache: dict[tuple[str, str, str, str], dict[str, Any]] = {}
        self.parameter_adapters: Any = None
        self.parameter_adapters_loaded = False
        self.parameter_metadata_checked = False
        self.parameter_metadata: Any = None
        self.parameter_document: Any = None
        self.parameter_contracts: dict[str, tuple[Any, Any, str] | None] = {}
        self.parameter_information_checked = False
        self.parameter_information_policy: Any = None
        self.parameter_information_contract: tuple[Any, Any, str] | None = None
        self.parameter_native_inputs: dict[str, tuple[str, str]] = {}
        # With an incomplete definition index, an unrecognized condition name
        # could be a custom trigger rather than a built-in. Do not infer safety
        # from a caller supplying only the consumer files.
        self.source_gaps: list[dict[str, Any]] = []
        for source in sorted(set(source_hashes) | set(effective.failures)):
            if not source.endswith(".txt") or _family(source) not in {
                "script_values",
                "scripted_triggers",
            }:
                continue
            if source in native.roots and source in effective.roots:
                continue
            status = (
                "source_parse_failure"
                if source in native.failures or source in effective.failures
                else "source_missing"
            )
            self.source_gaps.append(
                {
                    "family": _family(source),
                    "definition": f"@source:{source}",
                    "status": status,
                    "native_source": source,
                    "effective_source": source if source in effective_bytes else None,
                    "native_source_sha256": hashlib.sha256(native_bytes[source]).hexdigest()
                    if source in native_bytes
                    else None,
                    "effective_source_sha256": hashlib.sha256(effective_bytes[source]).hexdigest()
                    if source in effective_bytes
                    else None,
                    "native_ast_sha256": None,
                    "effective_ast_sha256": None,
                }
            )


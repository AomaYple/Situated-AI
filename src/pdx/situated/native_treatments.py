def _implicit_conditions_known(
    node: Assignment,
    contract: Mapping[str, Any],
    native: _Sources,
    parameters: Mapping[str, Any],
) -> bool:
    """Validate actual optional-leaf readers with the existing finite type API.

    Parameter/resource queries and generated helpers need an independent exact
    argument/source contract. The fixture evaluator's generic syntax acceptance
    is deliberately insufficient for those calls or arbitrary scalar names.
    """
    from .. import decision_interfaces, decision_rules  # noqa: PLC0415, TID252

    root_scope = contract["actor_scope"]
    actor_path = ("owner",) if root_scope == "state" else ()

    def transition(scope: str, key: str) -> str | None:
        if (scope, key) in {("state", "owner"), ("country", "market")}:
            return "country" if key == "owner" else "market"
        for prefix, before, after, family in (
            ("mg:", "market", "market_goods", "goods"),
            ("sg:", "state", "state_goods", "goods"),
            ("ig:", "country", "interest_group", "interest_groups"),
        ):
            if scope == before and key.startswith(prefix):
                return after if len(native.owners[family, key[len(prefix) :]]) == 1 else None
        return None

    def condition(block: Block, scope: str, path: tuple[str, ...]) -> bool:
        if not block.items:
            return False
        for item in block.items:
            if not isinstance(item, Assignment) or item.prefix is not None:
                return False
            if (("ROOT", *path), _digest(item)) in parameters.get("clauses", set()):
                continue
            if (
                scope == "country"
                and _Dependencies.registered_country_helper(("scripted_triggers", item.key))
                and _literal(item, "yes")
            ):
                continue
            if item.key in {"AND", "OR", "NOT"}:
                if (
                    item.op != "="
                    or not isinstance(item.value, Block)
                    or not condition(item.value, scope, path)
                ):
                    return False
            elif isinstance(item.value, Block):
                next_scope = root_scope if item.key == "ROOT" else transition(scope, item.key)
                next_path = () if item.key == "ROOT" else (*path, item.key)
                if (
                    item.op != "="
                    or next_scope is None
                    or not condition(item.value, next_scope, next_path)
                ):
                    return False
            elif not isinstance(item.value, Scalar) or item.value.quoted:
                return False
            elif item.key == "always":
                if item.op != "=" or item.value.text not in {"yes", "no"}:
                    return False
            elif item.key == "exists":
                if item.op != "=" or (
                    item.value.text != "ROOT" and transition(scope, item.value.text) is None
                ):
                    return False
            else:
                signature = decision_interfaces._INPUTS.get(item.key)
                if signature is None or item.key in pdx_eval._PARAMETER_QUERIES:
                    return False
                kind = signature[1]
                if kind == "boolean":
                    if item.op != "=" or item.value.text not in {"yes", "no"}:
                        return False
                elif item.op not in {"=", ">", ">=", "<", "<="} or not _NUMBER.fullmatch(
                    item.value.text
                ):
                    return False
                reader = decision_rules.Reader(
                    key=item.key,
                    engine=item.key,
                    scope="root",
                    path=path,
                    unit=decision_interfaces._UNITS.get(item.key, "boolean"),
                    kind=kind,
                )
                try:
                    if (
                        decision_interfaces.reader_scope(reader, actor_path, native_root=root_scope)
                        != scope
                    ):
                        return False
                except ValueError:
                    return False
        return True

    def visit(value: Block | Scalar | None) -> bool:
        if not isinstance(value, Block):
            return True
        return all(
            isinstance(item, Assignment)
            and (
                isinstance(item.value, Block) and condition(item.value, root_scope, ())
                if item.key == "limit"
                else visit(item.value)
            )
            for item in value.items
        )

    return visit(node.value)


def _implicit_numeric_projections(
    inventory: VanillaInventory,
    coverage: Mapping[str, Any] | None,
    native: _Sources,
    effective: _Sources,
    dependencies: _Dependencies,
) -> dict[str, dict[int, dict[str, Any]]]:
    """Project only independently documented, actually validated optional leaves.

    This does not add rows to the native denominator or grant a business exit.
    The authoritative implicit contract is recomputed from pinned source bytes;
    receipt scope/action claims alone cannot authorize additions or their AST.
    """
    from .domain_coverage import NativeConsumerBinding, _NativeBindingProofs  # noqa: PLC0415
    from .vanilla_inventory import VanillaSurface  # noqa: PLC0415

    result: dict[str, dict[int, dict[str, Any]]] = defaultdict(dict)
    if coverage is None or not dependencies.production_complete or dependencies.source_gaps:
        return result
    _, issues = _coverage_rows(inventory, coverage)
    rows = coverage.get("implicit_rows")
    if issues or not isinstance(rows, list) or inventory.parse_failures:
        return result
    identities = [
        (row.get("source"), row.get("definition"), row.get("field"))
        for row in rows
        if isinstance(row, dict)
    ]
    if len(identities) != len(rows) or any(
        not all(isinstance(value, str) for value in identity) for identity in identities
    ):
        return result
    counts = Counter(identities)
    contracts = _NativeBindingProofs(inventory, dependencies.native_bytes, {})
    for row, identity in zip(rows, identities, strict=True):
        source, definition, field = identity
        assert isinstance(source, str)
        assert isinstance(definition, str)
        assert isinstance(field, str)
        if (
            counts[identity] != 1
            or source not in native.roots
            or source not in effective.roots
            or native.owners[_family(source), definition] != [source]
            or effective.owners[_family(source), definition] != [source]
            or any(_family(failed) == _family(source) for failed in effective.failures)
        ):
            continue
        try:
            binding = NativeConsumerBinding(source, definition, field)
            contract = contracts.implicit_building(binding) or contracts.implicit_company(binding)
        except (KeyError, TypeError, ValueError):
            continue
        covered = row.get("covered_actions")
        matched = row.get("matched_actions")
        if (
            contract is None
            or any(
                type(row.get(key)) is not type(value) or row.get(key) != value
                for key, value in contract.items()
            )
            or not isinstance(covered, list)
            or not covered
            or any(not isinstance(action, str) or not action for action in covered)
            or len(set(covered)) != len(covered)
            or not isinstance(matched, list)
            or any(action not in matched for action in covered)
            or row.get("binding_issues") != {}
        ):
            continue
        before, before_state = _resolve(native.roots[source], definition, field)
        after, after_state = _resolve(effective.roots[source], definition, field)
        if (
            before is not None
            or before_state != "missing"
            or after is None
            or after_state != "found"
            or not _numeric_shape(after)
            or not _implicit_conditions_known(
                after,
                contract,
                native,
                dependencies.parameter_readers(source, definition, field, contract["actor_scope"]),
            )
            or not _variable_boundary(native.roots[source], effective.roots[source])
        ):
            continue
        # There is no native expression at this optional field. Comparing it
        # to itself would falsely inherit new opaque operands or dependencies.
        empty = Assignment(after.key, "=", Block([]))
        implicit_surface = VanillaSurface(
            surface_id=f"implicit:{source}:{definition}.{field}",
            source=source,
            definition=definition,
            field=field,
            actor_scope=contract["actor_scope"],
            target_scope=contract["target_scope"],
            operation=contract["operation"],
            capability="direct",
            status="pending",
            getter=None,
            getter_note="independently_bound_optional_numeric_leaf",
            scope_evidence=tuple(contract["evidence"]),
            responsibility_step="D0",
            source_line=after.line,
        )
        proofs, closed = dependencies.check(empty, after, numeric=True, surface=implicit_surface)
        if not closed:
            continue
        result[source][id(after)] = {
            **contract,
            "covered_actions": list(covered),
            "effective_ast_sha256": _digest(after),
            "effective_source_sha256": hashlib.sha256(
                dependencies.effective_bytes[source]
            ).hexdigest(),
            "dependencies": proofs,
        }
    return result


def _supply_enum_projections(dependencies: _Dependencies) -> dict[str, dict[int, dict[str, Any]]]:
    """Prove complete enum additions and the three pinned idempotent unions.

    Appends disappear from the boundary comparison; each reviewed union restores
    its exact native AST. No other native stance or sibling may change, and this
    projection grants no numeric control or action execution eligibility.
    """
    from .. import decision_adapters, decision_interfaces, decision_rules  # noqa: PLC0415, TID252
    from . import engine_scope, supply_program  # noqa: PLC0415
    from .vanilla_inventory import _parameter_evidence_contract  # noqa: PLC0415

    source = "common/ai_strategies/00_default_strategy.txt"
    if (
        not dependencies.production_complete
        or source not in dependencies.native.roots
        or source not in dependencies.effective.roots
        or ".metadata/metadata.json" not in dependencies.effective_bytes
        or dependencies.source_gaps
        or dependencies.effective.failures
        or dependencies.native_bytes != dependencies.parameter_input_mappings[0]
        or dependencies.effective_bytes != dependencies.parameter_input_mappings[1]
    ):
        return {}
    try:
        contract = dependencies._parameter_contract(source)
        adapters = dependencies.parameter_adapters
        plan = adapters.supply
        metadata = dependencies.parameter_metadata
        if (
            contract is None
            or plan is None
            or plan.source != source
            or not any("market" in policy.enabled_domains for _, policy in adapters.policies)
            or metadata is None
            or metadata.get("supply_program_generator_sha256")
            != hashlib.sha256(Path(supply_program.__file__).read_bytes()).hexdigest()
        ):
            return {}
        expected_metadata = {
            "source": source,
            "field": "ai_strategy_default.goods_stances",
            "goods": list(plan.goods),
            "price_threshold": plan.price_threshold,
            "stance": "wants_high_supply",
            "conditions": [
                "is_ai",
                "existing_market_goods",
                "price_above_threshold",
                "negative_market_goods_delta",
            ],
            "consumer": "vanilla_production_and_trade_planning",
            "behavior_verified": False,
            "limits": "market_aggregate_not_national_import_dependency; active_strategy_overrides_retained; no_forced_trade_or_production_method",
            "consumer_programs": [program.as_dict() for program in plan.actions()],
        }
        if metadata.get("supply_plan") != expected_metadata:
            return {}
        writes = decision_adapters.writes(adapters)
        if (
            [row for row in writes if row[2] == "supply_plan"]
            != [
                (source, ("ai_strategy_default", "goods_stances", good), "supply_plan")
                for good in sorted(plan.goods)
            ]
            or not plan.goods
            or len(set(plan.goods)) != len(plan.goods)
        ):
            return {}
        strategy = json.loads(engine_scope.strategy_snapshot())
        evidence_hashes = _parameter_evidence_contract()
        pins = {
            source: strategy["script_hashes"][source],
            **{
                name: evidence_hashes[name]
                for name in (
                    "common/goods/00_goods.txt",
                    "common/alert_types/00_alert_types.txt",
                    "common/objective_subgoals/00_subgoals_tutorial.txt",
                )
            },
        }
        for name, sha in pins.items():
            raw = dependencies.native_bytes.get(name)
            if raw is None or hashlib.sha256(raw).hexdigest() != sha:
                return {}
            if name != source and dependencies.effective_bytes.get(name) != raw:
                return {}
        native, effective = dependencies.native, dependencies.effective
        for roots in (native, effective):
            if roots.owners["ai_strategies", "ai_strategy_default"] != [source]:
                return {}
        before, bstate = _resolve(native.roots[source], "ai_strategy_default", "goods_stances")
        after, astate = _resolve(effective.roots[source], "ai_strategy_default", "goods_stances")
        if (
            before is None
            or after is None
            or bstate != "found"
            or astate != "found"
            or not isinstance(before.value, Block)
            or not isinstance(after.value, Block)
        ):
            return {}
        template, state = _resolve(
            native.roots[source], "ai_strategy_default", "goods_stances.grain"
        )
        original_template = parse_bytes(
            b"grain={stance=wants_high_supply trigger={has_famine=yes}}", path="native-stance"
        ).root.items[0]
        if template is None or state != "found" or _ast(template) != _ast(original_template):
            return {}
        # Read actual original scoped getter uses, not a bag of recognized words.
        alert, state = _resolve(
            native.roots["common/alert_types/00_alert_types.txt"],
            "expensive_government_goods_alert",
            "valid.market_goods_pricier",
        )
        expected_alert = parse_bytes(b"market_goods_pricier>0.25", path="native-price").root.items[
            0
        ]
        alert_scope, scope_state = _resolve(
            native.roots["common/alert_types/00_alert_types.txt"],
            "expensive_government_goods_alert",
            "script_context",
        )
        expected_scope = parse_bytes(
            b"script_context=player_market_goods", path="native-price-scope"
        ).root.items[0]
        tutorial = native.roots["common/objective_subgoals/00_subgoals_tutorial.txt"]
        balance = parse_bytes(
            b"market={mg:tools={market_goods_delta>=10}}", path="native-balance"
        ).root.items[0]

        def contains(value: Assignment | Block | Scalar | None, path: tuple[str, ...] = ()) -> bool:
            if path == (
                "sg_change_production_method",
                "trigger",
                "any_scope_state",
                "OR",
                "AND",
                "market",
            ) and _ast(value) == _ast(balance):
                return True
            if isinstance(value, Assignment):
                return contains(value.value, path)
            return isinstance(value, Block) and any(
                contains(item, (*path, item.key) if isinstance(item, Assignment) else path)
                for item in value.items
            )

        if (
            alert is None
            or state != "found"
            or _ast(alert) != _ast(expected_alert)
            or alert_scope is None
            or scope_state != "found"
            or _ast(alert_scope) != _ast(expected_scope)
            or not contains(tutorial)
        ):
            return {}
        native_stances = {stance.good: stance for stance in plan.native_stances}
        if native_stances:
            reviewed = supply_program.native_stances_1151()
            if (
                plan.native_stances != reviewed
                or (set(before.value.keys()) & set(plan.goods)) != native_stances.keys()
            ):
                return {}
        result = {}
        restored: dict[int, Assignment] = {}
        for good in plan.goods:
            goods_source = "common/goods/00_goods.txt"
            if native.owners["goods", good] != [goods_source] or effective.owners[
                "goods", good
            ] != [goods_source]:
                return {}
            for engine, unit in (
                ("market_goods_pricier", "price_above_base_ratio"),
                ("market_goods_delta", "sell_minus_buy_orders"),
            ):
                reader = decision_rules.Reader(
                    "supply", engine, "root", unit, "number", path=("market", f"mg:{good}")
                )
                if (
                    decision_interfaces.reader_scope(reader, (), native_root="country")
                    != "market_goods"
                ):
                    return {}
            nodes = after.value.all(good)
            if len(nodes) != 1:
                return {}
            scarcity = (
                f"is_ai=yes exists=market market={{exists=mg:{good} "
                f"mg:{good}={{market_goods_pricier>{plan.price_threshold!r} "
                "market_goods_delta<0}}"
            )
            original = before.value.all(good)
            if good in native_stances:
                stance = native_stances[good]
                native_text = dependencies.native_bytes[source].decode("utf-8-sig")
                start, end = supply_program.block_span(
                    native_text, ("ai_strategy_default", "goods_stances", good)
                )
                if len(original) != 1 or native_text[start:end] != stance.body:
                    return {}
                trigger_start, trigger_end = supply_program.block_span(
                    stance.body, ("<anonymous>", "trigger")
                )
                native_trigger = stance.body[trigger_start:trigger_end]
                # Independent expected shape: exactly one value, complete native
                # trigger as the first AND, and the independently scoped scarcity
                # trigger as the second. Do not call the production compose/render.
                expected_text = (
                    f"{good}={{stance=wants_high_supply trigger={{OR={{AND="
                    + native_trigger
                    + " AND={"
                    + scarcity
                    + "}}}}"
                )
            else:
                if original:
                    return {}
                expected_text = f"{good}={{stance=wants_high_supply trigger={{{scarcity}}}}}"
            expected = parse_bytes(
                expected_text.encode(),
                path="registered-supply-stance",
            )
            if expected.errors or len(nodes) != 1 or _ast(nodes[0]) != _ast(expected.root.items[0]):
                return {}
            if good in native_stances:
                # Reconstruct from the actual emitted native arm and its actual
                # stance/siblings. The expected full OR above proves the unique
                # ordinary shape; inserting the baseline here would conceal a
                # broken restoration implementation behind a trusted digest.
                actual_body = nodes[0].value
                assert isinstance(actual_body, Block)
                actual_trigger = actual_body.first("trigger")
                assert actual_trigger is not None
                assert isinstance(actual_trigger.value, Block)
                actual_union = actual_trigger.value.first("OR")
                assert actual_union is not None
                assert isinstance(actual_union.value, Block)
                native_arm = actual_union.value.items[0]
                assert isinstance(native_arm, Assignment)
                restored_trigger = replace(actual_trigger, value=native_arm.value)
                restored_node = replace(
                    nodes[0],
                    value=replace(
                        actual_body,
                        items=[
                            restored_trigger if item is actual_trigger else item
                            for item in actual_body.items
                        ],
                    ),
                )
                if _ast(restored_node) != _ast(original[0]):
                    return {}
                restored[id(nodes[0])] = restored_node
            result[id(nodes[0])] = {
                "source": source,
                "definition": "ai_strategy_default",
                "field": f"goods_stances.{good}",
                "kind": "registered_enum_idempotent_or"
                if good in native_stances
                else "registered_enum_addition",
                "effective_ast_sha256": _digest(nodes[0]),
                **(
                    {"restored_native_ast_sha256": _digest(restored[id(nodes[0])])}
                    if good in native_stances
                    else {}
                ),
                "native_sources": pins,
                "contract_sha256": hashlib.sha256(
                    json.dumps(expected_metadata, sort_keys=True).encode()
                ).hexdigest(),
                "interface_authorized": True,
                "business_complete": False,
            }
        restored_table = Block(
            [
                restored.get(id(item), item)
                for item in after.value.items
                if id(item) not in result or id(item) in restored
            ]
        )
        if _ast(restored_table) != _ast(before.value):
            return {}
        return {source: result}
    except (KeyError, TypeError, AttributeError, UnicodeError, ValueError):
        return {}


def _responsibility_axes(
    rows: list[dict[str, Any]],
    inventory: VanillaInventory,
    native: _Sources,
    effective: _Sources,
    dependencies: _Dependencies,
    generated_sources: Mapping[str, bytes],
    production_complete: bool,
    implicit_projections: Mapping[str, Mapping[int, dict[str, Any]]],
) -> None:
    """Close complete source boundaries independently of interface permission.

    Mixed files may replace only independently corroborated typed numeric leaves.
    Comparing the rest of the entire AST preserves parents, order, local variables
    and every other reference. No field-only equality can prove this boundary.
    """
    by_source: dict[str, list[tuple[VanillaSurface, dict[str, Any]]]] = defaultdict(list)
    enum_projections = _supply_enum_projections(dependencies)
    for surface, row in zip(inventory.surfaces, rows, strict=True):
        by_source[surface.source].append((surface, row))
    for source, members in by_source.items():
        before, after = native.roots.get(source), effective.roots.get(source)
        implicit = implicit_projections.get(source, {})
        enums = enum_projections.get(source, {})
        additions = {**implicit, **enums}
        masks_before: dict[int, str] = {}
        masks_after: dict[int, str] = {}
        for surface, row in members:
            if row["status"] != "implemented_numeric" or before is None or after is None:
                continue
            bnode, bstate = _resolve(before, surface.definition, surface.field)
            anode, astate = _resolve(after, surface.definition, surface.field)
            if bnode is not None and anode is not None and bstate == astate == "found":
                masks_before[id(bnode)] = surface.declaration_id
                masks_after[id(anode)] = surface.declaration_id

        def boundary(
            value: Assignment | Block | Scalar | None,
            masks: Mapping[int, str],
            additions: Mapping[int, dict[str, Any]] = additions,
            enums: Mapping[int, dict[str, Any]] = enums,
            before: Block | None = before,
        ) -> object:
            if isinstance(value, Assignment):
                projection = enums.get(id(value))
                if projection is not None and projection["kind"] == "registered_enum_idempotent_or":
                    assert before is not None
                    original, state = _resolve(
                        before, projection["definition"], projection["field"]
                    )
                    assert original is not None
                    assert state == "found"
                    return _ast(original)
                if id(value) in masks:
                    return [
                        "typed_numeric_change",
                        value.key,
                        value.op,
                        value.prefix,
                        masks[id(value)],
                    ]
                return [
                    "assignment",
                    value.key,
                    value.op,
                    value.prefix,
                    boundary(value.value, masks),
                ]
            if isinstance(value, Block):
                return [
                    "block",
                    [
                        boundary(item, masks)
                        for item in value.items
                        if id(item) not in additions
                        or additions[id(item)].get("kind") == "registered_enum_idempotent_or"
                    ],
                ]
            return _ast(value)

        identical = before is not None and after is not None and _ast(before) == _ast(after)
        context_closed = (
            before is not None
            and after is not None
            and boundary(before, masks_before) == boundary(after, masks_after)
        )
        closed = (
            not dependencies.source_gaps
            and before is not None
            and after is not None
            and _variable_boundary(before, after)
        )
        if before is not None:
            # Native references outside a changed numeric leaf remain part of
            # the protected source. New references inside masked leaves have
            # already passed that leaf's independent dependency check.
            for node in before.assignments():
                _, valid = dependencies.check(
                    node, node, numeric=_family(source) == "script_values"
                )
                closed = closed and valid
        for surface, row in members:
            bnode = _declaration(before, surface) if before is not None else None
            anode = _declaration(after, surface) if after is not None else None
            structural_projection = (
                row["native_role"] == "structural_container"
                and row["ast_status"] == "changed"
                and bnode is not None
                and anode is not None
                and boundary(bnode, masks_before) == boundary(anode, masks_after)
            )
            enum_binding = enums.get(id(anode)) if anode is not None else None
            native_enum_projection = bool(
                enum_binding is not None
                and enum_binding["kind"] == "registered_enum_idempotent_or"
                and (enum_binding["source"], enum_binding["definition"], enum_binding["field"])
                == (surface.source, surface.definition, surface.field)
                and row["ast_status"] == "changed"
                and bnode is not None
                and anode is not None
                and row["native_ast_sha256"] == enum_binding["restored_native_ast_sha256"]
                and row["effective_ast_sha256"] == enum_binding["effective_ast_sha256"]
                and boundary(bnode, masks_before) == boundary(anode, masks_after)
            )
            source_issues = []
            if not production_complete:
                source_issues.append("production_manifest_incomplete")
            if not context_closed:
                source_issues.append("source_parent_variable_or_reference_boundary_unproven")
            if not closed:
                source_issues.append("source_dependency_closure_unproven")
            if row["native_ast_sha256"] is None or row["effective_ast_sha256"] is None:
                source_issues.append("physical_declaration_unresolved")
            if row["ast_status"] != "retained" and not (
                structural_projection or native_enum_projection
            ):
                source_issues.append("native_declaration_changed_or_unresolved")
            protected = not source_issues
            row["source_protection"] = {
                "status": "retained"
                if protected
                else "changed"
                if row["ast_status"] == "changed"
                else "unproven",
                "proven": protected,
                "mode": "whole_source_inherited"
                if source not in generated_sources
                else "whole_source_identical"
                if identical
                else "mixed_override",
                "dependencies_closed": closed,
                "context_closed": context_closed,
                "structural_projection": structural_projection,
                "native_enum_projection": native_enum_projection,
                "native_enum_binding": enum_binding if native_enum_projection else None,
                "controlled_numeric_declarations": sorted(masks_before.values()),
                "implicit_numeric_projections": list(implicit.values()),
                "implicit_enum_projections": list(enums.values()),
                "issues": source_issues,
                "native_source_sha256": hashlib.sha256(
                    dependencies.native_bytes[source]
                ).hexdigest()
                if source in dependencies.native_bytes
                else None,
                "effective_source_sha256": hashlib.sha256(
                    dependencies.effective_bytes[source]
                ).hexdigest()
                if source in dependencies.effective_bytes
                else None,
            }
    for surface, row in zip(inventory.surfaces, rows, strict=True):
        known = (
            row["interface_kind"] != "needs_review"
            and surface.legal
            and not surface.ambiguity
            and "duplicate_field_merge_semantics_unknown" not in row["issues"]
            and surface.surface_id not in inventory.unknown_scopes
            and not inventory.parse_failures
        )
        row["interface"] = {
            "known": known,
            "kind": row["interface_kind"],
            "scope_known": surface.actor_scope != "unknown" and surface.target_scope != "unknown",
            "control_authorized": (
                row["status"] == "implemented_numeric"
                and production_complete
                and row["source_protection"]["context_closed"]
                and row["source_protection"]["dependencies_closed"]
            ),
        }
        changed_dependency = any(
            proof["status"]
            not in {"retained", "retained_opaque", "proven_generated", "proven_parameter_reader"}
            and (
                proof["native_ast_sha256"] != proof["effective_ast_sha256"]
                or (proof["native_source"] is None and proof["effective_source"] is not None)
            )
            for proof in row["dependencies"]
        )
        row["active_unknown_usage"] = bool(
            not (
                row["source_protection"]["proven"]
                and (
                    row["source_protection"]["structural_projection"]
                    or row["source_protection"]["native_enum_projection"]
                )
            )
            and (
                changed_dependency
                or (
                    row["ast_status"] == "changed"
                    and (
                        not known
                        or "generated_numeric_shape_unproven" in row["issues"]
                        or not row["source_protection"]["context_closed"]
                        or not row["source_protection"]["dependencies_closed"]
                    )
                )
            )
        )
        row["business_obligation"] = {
            "disposition": "control_binding"
            if row["interface"]["control_authorized"]
            else "preserve_native"
            if row["source_protection"]["proven"]
            else "unresolved",
            "complete": False,
        }


def native_treatments(
    inventory: VanillaInventory,
    native_sources: Mapping[str, bytes],
    generated_sources: Mapping[str, bytes],
    *,
    coverage: Mapping[str, Any] | None = None,
    production_complete: bool = False,
    _metadata: _AuditMetadata | None = None,
) -> dict[str, Any]:
    """Retain every declaration and independently check native protection duties.

    Native source hash drift and unsafe/alias paths fail rather than accepting
    a different baseline. Missing bytes, malformed/duplicate declarations and
    unproven scopes remain explicit rows; none are reclassified unsupported.
    """
    if type(production_complete) is not bool:
        raise ValueError("native treatment production manifest assertion must be boolean")
    aliases: dict[str, str] = {}
    for mapping in (native_sources, generated_sources):
        seen: set[str] = set()
        for source, raw in mapping.items():
            _path(source)
            if not isinstance(raw, bytes):
                raise ValueError("native treatment sources must be bytes")
            if source.casefold() in seen:
                raise ValueError("native treatment path alias")
            if aliases.get(source.casefold(), source) != source:
                raise ValueError("native treatment path alias")
            aliases[source.casefold()] = source
            seen.add(source.casefold())
    for source, raw in native_sources.items():
        if hashlib.sha256(raw).hexdigest() != inventory.source_hashes.get(source):
            raise ValueError(f"native treatment source SHA mismatch: {source}")
    ids = [surface.declaration_id for surface in inventory.surfaces]
    if len(set(ids)) != len(ids):
        raise ValueError("native treatment declaration IDs are duplicated")
    native = _Sources(native_sources)
    effective_bytes = {**native_sources, **generated_sources}
    effective = _Sources(effective_bytes, reuse=native)
    dependencies = _Dependencies(
        native,
        effective,
        native_sources,
        effective_bytes,
        inventory.source_hashes,
        production_complete=production_complete,
        _metadata=_metadata,
    )
    covered, receipt_issues = _coverage_rows(inventory, coverage)
    from . import r2_native  # noqa: PLC0415

    try:
        network_bindings = {
            (item.source, item.definition, item.field): item
            for item in r2_native.production_bindings(
                generated_sources, native_sources, metadata=_metadata
            )
        }
    except (KeyError, TypeError, AttributeError, UnicodeError, ValueError):
        # A forged/malformed declaration grants no dependency projection. The
        # ordinary changed-source and unknown-usage checks still apply below.
        network_bindings = {}
    unknown_scopes = set(inventory.unknown_scopes)
    rows: list[dict[str, Any]] = []
    for surface in inventory.surfaces:
        row: dict[str, Any] = {
            "declaration_id": surface.declaration_id,
            "context_sha256": _context_digest(surface),
            "surface_id": surface.surface_id,
            "source": surface.source,
            "definition": surface.definition,
            "field": surface.field,
            "source_line": surface.source_line,
            "declaration_occurrence": surface.declaration_occurrence,
            "ambiguity": surface.ambiguity,
            "parent_field": surface.parent_field,
            "actor_scope": surface.actor_scope,
            "target_scope": surface.target_scope,
            "native_operation": surface.operation,
            "native_capability": surface.capability,
            "native_inventory_status": surface.status,
            "native_legal": surface.legal,
            "native_role": _native_role(surface),
            "scope_evidence": list(surface.scope_evidence),
            "interface_kind": "needs_review",
            "status": "missing_evidence",
            "ast_status": "missing",
            "native_ast_sha256": None,
            "effective_ast_sha256": None,
            "native_terminal": None,
            "effective_origin": "generated_override"
            if surface.source in generated_sources
            else "native_inherited",
            "companions": [],
            "issues": [],
            "implemented_numeric": False,
            "numeric_actions": [],
            "resolved_numeric_value": None,
            "dependencies": [],
            "business_complete": False,
        }
        rows.append(row)
        issues = row["issues"]
        nroot = native.roots.get(surface.source)
        if nroot is None:
            issues.append(
                "native_parse_failure"
                if surface.source in native.failures
                else "native_bytes_missing"
            )
            continue
        family = _family(surface.source)
        physical = _declarations(nroot, surface.definition, surface.field)
        node = _declaration(nroot, surface)
        if node is None:
            row["ast_status"] = "missing"
            issues.append("native_declaration_occurrence_missing")
            continue
        row["native_ast_sha256"] = _digest(node)
        row["native_terminal"] = _native_terminal(surface, node)
        row["interface_kind"] = _kind(surface, node)
        if node.line != surface.source_line:
            issues.append("native_source_line_mismatch")
            continue
        if len(set(native.owners[family, surface.definition])) != 1:
            row["ast_status"] = "ambiguous"
            issues.append("native_definition_ambiguous")
            continue
        if surface.source not in generated_sources and not production_complete:
            issues.append("production_manifest_incomplete")
            continue
        eroot = effective.roots.get(surface.source)
        if eroot is None:
            issues.append("production_parse_failure")
            continue
        if any(_family(source) == family for source in effective.failures):
            issues.append("production_family_parse_failure")
            continue
        enode, resolution = _resolve(eroot, surface.definition, surface.field)
        if (len(physical) > 1 and _ast(nroot) == _ast(eroot)) or (
            family == "defines"
            and len(physical) == 1
            and len(_declarations(eroot, surface.definition, surface.field)) == 1
        ):
            # This selects a physical occurrence, never first/last-key engine
            # precedence. Repeated field semantics remain an explicit unknown.
            enode = _declaration(eroot, surface)
            resolution = "found" if enode is not None else "missing"
        if enode is None:
            row["ast_status"] = resolution
            issues.append(f"production_field_{resolution}")
            continue
        if len(set(effective.owners[family, surface.definition])) != 1:
            row["ast_status"] = "ambiguous"
            issues.append("production_definition_ambiguous")
            continue
        row["effective_ast_sha256"] = _digest(enode)
        if len(physical) > 1:
            issues.append("duplicate_field_merge_semantics_unknown")
        same = _ast(node) == _ast(enode)
        row["ast_status"] = "retained" if same else "changed"
        kind = row["interface_kind"]
        effective_consumer = enode
        continuous_proof = {}
        network_binding = network_bindings.get((surface.source, surface.definition, surface.field))
        network_proof = (
            r2_native.dependency_proof(network_binding)
            if network_binding is not None
            and dependencies.production_complete
            and not dependencies.source_gaps
            and not dependencies.effective.failures
            and r2_native.native_issue(network_binding, surface) is None
            and network_binding.native_ast_sha256 == row["native_ast_sha256"]
            and network_binding.effective_ast_sha256 == row["effective_ast_sha256"]
            else {}
        )
        if not same and kind == "dynamic_numeric":
            continuous_proof = _support_program_proof(
                surface, inventory, dependencies, generated_sources
            )
        if continuous_proof or network_proof:
            # The complete typed program and restored native tail were already
            # checked as one overlay. Re-run dependency closure on the untouched
            # native node so generated program operands cannot borrow opaque names.
            main_proofs, dependencies_proven = dependencies.check(
                node, node, numeric=True, surface=surface
            )
            main_proofs.append(continuous_proof or network_proof)
        elif not same and kind == "dynamic_numeric" and not _numeric_shape(enode, node):
            row["resolved_numeric_value"] = _registered_numeric_value(
                surface, enode, effective, generated_sources
            )
            if row["resolved_numeric_value"] is None:
                issues.append("generated_numeric_shape_unproven")
            else:
                resolved = row["resolved_numeric_value"]
                helper, state = _resolve(
                    effective.roots[resolved["source"]], resolved["definition"], "__body__"
                )
                assert helper is not None
                assert state == "found"
                # The new helper name has an exact registered source/consumer
                # proof above. Its actual body still requires dependency audit.
                effective_consumer = helper
        if not (continuous_proof or network_proof):
            main_proofs, dependencies_proven = dependencies.check(
                node,
                effective_consumer,
                numeric=kind == "dynamic_numeric",
                surface=surface,
            )
        dependency_proofs = {(proof["family"], proof["definition"]): proof for proof in main_proofs}
        for field in _companion_fields(surface):
            before, bstate = _resolve(nroot, surface.definition, field)
            after, astate = _resolve(eroot, surface.definition, field)
            if before is None and after is None and bstate == astate == "missing":
                continue
            companion_same = bstate == astate == "found" and _ast(before) == _ast(after)
            companion_proofs, companion_dependencies_proven = dependencies.check(
                *(item for item in (before, after) if item is not None),
                numeric=False,
                surface=surface,
            )
            dependencies_proven = dependencies_proven and companion_dependencies_proven
            dependency_proofs.update(
                ((proof["family"], proof["definition"]), proof) for proof in companion_proofs
            )
            row["companions"].append(
                {
                    "field": field,
                    "retained": companion_same and companion_dependencies_proven,
                    "ast_retained": companion_same,
                    "dependencies": companion_proofs,
                    "native_ast_sha256": _digest(before),
                    "effective_ast_sha256": _digest(after),
                }
            )
            if not companion_same:
                issues.append(f"native_companion_changed:{field}")
            if not companion_dependencies_proven:
                issues.append(f"native_companion_dependency_unproven:{field}")
        row["dependencies"] = [dependency_proofs[key] for key in sorted(dependency_proofs)]
        if not dependencies_proven:
            issues.append("native_dependency_unproven")
        if not same:
            if kind == "eligibility":
                issues.append("native_eligibility_changed")
            elif kind == "completion_observation":
                issues.append("completion_condition_changed")
            elif kind == "lifecycle_effect":
                issues.append("lifecycle_effect_changed")
            if row["native_terminal"] == "zero":
                issues.append("native_zero_changed_unproven")
        unproven = (
            kind == "needs_review"
            or not surface.legal
            or bool(surface.ambiguity)
            or surface.surface_id in unknown_scopes
            or bool(inventory.parse_failures)
            or not dependencies_proven
            or len(physical) > 1
        )
        if unproven:
            row["status"] = "needs_review"
            issues.append("native_interface_or_scope_needs_review")
        elif same and not issues:
            row["status"] = "retained_native"
        elif (
            kind == "dynamic_numeric"
            and not issues
            and _numeric_binding(surface, covered.get(surface.declaration_id, {}))
        ):
            row["status"] = "implemented_numeric"
            row["implemented_numeric"] = True
            row["numeric_actions"] = list(covered[surface.declaration_id]["covered_actions"])
        else:
            row["status"] = "changed_native"
    implicit_projections = _implicit_numeric_projections(
        inventory, coverage, native, effective, dependencies
    )
    _responsibility_axes(
        rows,
        inventory,
        native,
        effective,
        dependencies,
        generated_sources,
        production_complete,
        implicit_projections,
    )
    counts = Counter(row["status"] for row in rows)
    return {
        "schema": 1,
        "evidence_category": "static_check",
        "baseline_id": inventory.baseline_id,
        "scope_hash": inventory.scope_hash,
        "denominator": len(inventory.surfaces),
        "source_hashes_verified": {
            source: inventory.source_hashes[source] for source in sorted(native_sources)
        },
        "production_hashes": {
            source: hashlib.sha256(raw).hexdigest()
            for source, raw in sorted(generated_sources.items())
        },
        "production_manifest_complete_asserted": production_complete,
        "counts": {status: counts[status] for status in _STATUSES},
        "interface_counts": dict(sorted(Counter(row["interface_kind"] for row in rows).items())),
        "responsibility_counts": {
            "source_protection_proven": sum(row["source_protection"]["proven"] for row in rows),
            "interface_known": sum(row["interface"]["known"] for row in rows),
            "active_unknown_usage": sum(row["active_unknown_usage"] for row in rows),
            "business_complete": 0,
        },
        "receipt_issues": receipt_issues,
        "rows": rows,
        "business_complete": False,
        "evidence": "typed_native_ast_protection_and_existing_numeric_mapping_only",
        "limits": [
            "retained_native is not implemented_numeric or functional acceptance",
            "coverage bindings do not prove generated expression equivalence or native tails",
            "numeric mappings do not prove business depth, AI behavior or runtime scope",
            "native inheritance relies on caller completeness; omitted outputs cannot be discovered",
            "modifier code-side route support remains unproven for individual types",
        ],
    }
